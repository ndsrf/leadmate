export type AppTextKey = keyof typeof ES_INTERFACE;
export type TextKey = AppTextKey | (string & {});
export type Catalog = Partial<Record<TextKey, string>>;

/**
 * Spanish text catalog. Interface keys are statically typed; content keys resolve dynamically from active content.
 */
export const es: Record<TextKey, string> = new Proxy(ES_INTERFACE as unknown as Record<TextKey, string>, {
  get(target, prop: string) {
    if (prop in target) return (target as any)[prop];
    return getContentCatalog()[prop];
  },
  has(target, prop: string) {
    return prop in target || prop in getContentCatalog();
  },
  ownKeys(target) {
    const keys = new Set([...Reflect.ownKeys(target), ...Reflect.ownKeys(getContentCatalog())]);
    return Array.from(keys);
  },
  getOwnPropertyDescriptor(target, prop: string) {
    if (prop in target) return Reflect.getOwnPropertyDescriptor(target, prop);
    const content = getContentCatalog();
    if (prop in content) {
      return {
        value: content[prop],
        writable: false,
        enumerable: true,
        configurable: true,
      };
    }
    return undefined;
  },
});
