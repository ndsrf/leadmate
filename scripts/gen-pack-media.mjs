// Bundles the stable pack's Dog Game illustrations and Shop product pictures so they show offline on first launch,
// before (or without) any content host: copies content/stable/games/<id>/media/* to assets/games/<id>/ and
// content/stable/shop/products/<id>/media/* to assets/shop/<id>/, then writes src/shell/content/packMediaRegistry.ts
// (PACK_MEDIA, keyed by the path inside the pack). Deterministic and rerunnable: the two asset folders are rebuilt from
// scratch every run, so a removed picture disappears too. Pictures added to the pack later still arrive over the air.
// Run: node scripts/gen-pack-media.mjs (also part of npm run release:prepare)
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const STABLE = join(ROOT, 'content', 'stable');
const REGISTRY = join(ROOT, 'src', 'shell', 'content', 'packMediaRegistry.ts');
const PICTURE = /\.(png|jpe?g|webp)$/i;
/** Ceiling for this bundle on top of the Lesson and Node art; raise it deliberately, not by accident. */
const BUDGET = 3 * 1024 * 1024;

/** Each kind of pack item whose media/ folder is bundled: where it lives in the pack and where it goes in assets/. */
const KINDS = [
  { pack: 'games', assets: join(ROOT, 'assets', 'games') },
  { pack: 'shop/products', assets: join(ROOT, 'assets', 'shop') },
];

const dirs = (p) => (existsSync(p) ? readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : []);

const entries = [];
let total = 0;
for (const kind of KINDS) {
  rmSync(kind.assets, { recursive: true, force: true });
  for (const id of dirs(join(STABLE, kind.pack))) {
    const media = join(STABLE, kind.pack, id, 'media');
    if (!existsSync(media)) continue;
    const files = readdirSync(media).filter((f) => PICTURE.test(f)).sort();
    for (const f of files) {
      const to = join(kind.assets, id);
      mkdirSync(to, { recursive: true });
      copyFileSync(join(media, f), join(to, f));
      total += statSync(join(to, f)).size;
      const rel = relative(dirname(REGISTRY), join(to, f)).split('\\').join('/');
      entries.push(`  '${kind.pack}/${id}/media/${f}': require('${rel}'),`);
    }
  }
}

writeFileSync(
  REGISTRY,
  `// generated by scripts/gen-pack-media.mjs from content/stable/{games,shop/products}/<id>/media — do not edit
import type { ImageSourcePropType } from 'react-native';

/** Every bundled Dog Game illustration and Shop product picture, by its path inside a pack: \`games/<id>/media/<file>\`, \`shop/products/<id>/media/<file>\`. */
export const PACK_MEDIA: Readonly<Record<string, ImageSourcePropType>> = {${entries.length ? `\n${entries.join('\n')}\n` : ''}};
`,
);
console.log(`✓ ${entries.length} pack pictures, ${(total / 1024 / 1024).toFixed(2)} MB; wrote ${relative(ROOT, REGISTRY)}`);
if (total > BUDGET) {
  console.error(`over the ${(BUDGET / 1024 / 1024).toFixed(0)} MB pack media budget: shrink the pictures or raise BUDGET on purpose`);
  process.exit(1);
}
