// Emits the subset of the design tokens the Phaser bundle needs, so the bundle never imports RN code.
// Source: src/shell/ui/tokens.json. Output: bundle/src/tokens.generated.ts (committed; sim:build and sim:embed rerun this).
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('src/shell/ui/tokens.json', 'utf8'));
const USED = ['bg', 'surface', 'overlay', 'ink', 'inkMuted', 'brand', 'brandEdge', 'onBrand', 'quiet', 'quietEdge', 'onQuiet', 'accent', 'info', 'infoEdge', 'locked'];
const color = Object.fromEntries(USED.map((k) => [k, tokens.color[k]]));
const num = (hex) => parseInt(hex.slice(1), 16);
const out = `// generated by scripts/gen-hud-tokens.mjs from src/shell/ui/tokens.json — do not edit
export const HUD_COLOR = ${JSON.stringify(color, null, 2)} as const;

/** The same colours as Phaser's 0xRRGGBB numbers. */
export const HUD_COLOR_NUM = {
${USED.map((k) => `  ${k}: 0x${num(tokens.color[k]).toString(16).padStart(6, '0')},`).join('\n')}
} as const;

export const HUD_RADIUS = ${JSON.stringify(tokens.radius)} as const;
export const HUD_DEPTH = ${tokens.depth.edge};
export const HUD_FONT = { display: ${JSON.stringify(tokens.type.display)} } as const;

/** The primary action (shell buttons and the Marker): same fill, edge, label colour and radius. */
export const HUD_PRIMARY_BUTTON = { fill: HUD_COLOR.brand, edge: HUD_COLOR.brandEdge, label: HUD_COLOR.onBrand, radius: HUD_RADIUS.md, depth: HUD_DEPTH } as const;

export const HUD_CSS_VARS = \`:root { ${Object.entries(color)
  .map(([k, v]) => `--lm-${k}: ${v};`)
  .join(' ')} --lm-radius-md: ${tokens.radius.md}px; --lm-radius-lg: ${tokens.radius.lg}px; --lm-depth: ${tokens.depth.edge}px; }\`;
`;
writeFileSync('bundle/src/tokens.generated.ts', out);
console.log('wrote bundle/src/tokens.generated.ts');
