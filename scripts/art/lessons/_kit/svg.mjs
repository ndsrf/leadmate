// Shared by render-lesson-art.mjs and lesson-art-sheet.mjs: loads the kit, inlines <use href="#id"> references so a
// rendered illustration is self-contained, and checks an illustration against the style rules (palette, no words).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(here, '../../../..');
export const KIT = join(here, 'kit.svg');
/** The most all Lesson pictures together may weigh. */
export const BUDGET = 6 * 1024 * 1024;

/** Every colour of the design system: each hex value anywhere in tokens.json, upper case, 6 digits. */
export function palette() {
  const tokens = readFileSync(join(ROOT, 'src/shell/ui/tokens.json'), 'utf8');
  return new Set([...tokens.matchAll(/#[0-9a-fA-F]{6}\b/g)].map((m) => m[0].toUpperCase()));
}

/** The kit's symbols by id, each as its inner markup. */
export function loadKit(path = KIT) {
  const svg = readFileSync(path, 'utf8');
  const kit = new Map();
  for (const m of svg.matchAll(/<symbol\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) kit.set(m[1], m[2].trim());
  return kit;
}

const attrs = (s) => Object.fromEntries([...s.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

/**
 * Replaces every `<use href="#id" .../>` with a group holding the symbol's markup (recursively), keeping the use's
 * transform, x / y and presentation attributes. Throws on an unknown id.
 */
export function inline(svg, kit) {
  let out = svg;
  for (let depth = 0; depth < 12; depth++) {
    let changed = false;
    out = out.replace(/<use\b([^>]*?)\/>/g, (whole, raw) => {
      const a = attrs(raw);
      const href = a.href ?? a['xlink:href'];
      if (!href?.startsWith('#')) return whole;
      const id = href.slice(1);
      if (!kit.has(id)) throw new Error(`unknown kit symbol: #${id}`);
      changed = true;
      const { href: _h, 'xlink:href': _x, x = '0', y = '0', transform = '', ...rest } = a;
      const t = `${transform} translate(${x} ${y})`.trim();
      const extra = Object.entries(rest).map(([k, v]) => ` ${k}="${v}"`).join('');
      return `<g transform="${t}"${extra}>${kit.get(id)}</g>`;
    });
    if (!changed) return out;
  }
  throw new Error('kit symbols nest too deep (a symbol uses itself?)');
}

const COLOUR_ATTR = /\b(fill|stroke|stop-color|flood-color|color)\s*[=:]\s*"?([^";>]+)/g;

/** Why an inlined illustration breaks the style rules: words, foreign content or colours outside the palette. */
export function problems(svg, colours = palette()) {
  const found = [];
  if (/<text\b/.test(svg)) found.push('has <text>: illustrations carry no words (the caption does)');
  for (const tag of ['image', 'foreignObject', 'script', 'style', 'linearGradient', 'radialGradient', 'filter']) if (new RegExp(`<${tag}\\b`).test(svg)) found.push(`has <${tag}>`);
  if (/href="(?!#)/.test(svg)) found.push('links outside the file');
  const bad = new Set();
  for (const m of svg.matchAll(COLOUR_ATTR)) {
    const value = m[2].trim();
    if (value === 'none' || value === 'currentColor' || value === 'transparent') continue;
    const hex = /^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/.exec(value)?.[1];
    const full = hex ? `#${hex.length === 3 ? [...hex].map((ch) => ch + ch).join('') : hex}`.toUpperCase() : null;
    if (!full || !colours.has(full)) bad.add(value);
  }
  if (bad.size > 0) found.push(`colours outside the palette: ${[...bad].join(', ')}`);
  return found;
}

/** A standalone SVG document of `inner` at `width` pixels, keeping the 640 by 360 canvas. */
export function sized(svg, width) {
  const height = Math.round((width * 9) / 16);
  return svg.replace(/<svg\b([^>]*)>/, (_m, a) => `<svg${a.replace(/\s(width|height)="[^"]*"/g, '')} width="${width}" height="${height}">`);
}

/**
 * Writes the registry of bundled Lesson pictures from every PNG present in `dir` (rendered art and control captures
 * alike), so it never drifts from the files. Returns how many there are and their total size in bytes.
 */
export function writeRegistry(dir, registry) {
  const pngs = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.png')).sort() : [];
  const total = pngs.reduce((sum, f) => sum + statSync(join(dir, f)).size, 0);
  const rel = relative(dirname(registry), dir).split('\\').join('/');
  const from = rel === '' ? '.' : rel.startsWith('.') ? rel : `./${rel}`;
  const entries = pngs.map((f) => `  '${basename(f, '.png')}': require('${from}/${f}'),`).join('\n');
  writeFileSync(
    registry,
    `// generated by scripts/render-lesson-art.mjs and scripts/capture-controls.mjs from assets/lessons/*.png — do not edit
import type { ImageSourcePropType } from 'react-native';

/** Every bundled Lesson illustration, by name. */
export const LESSON_ART: Readonly<Record<string, ImageSourcePropType>> = {${entries ? `\n${entries}\n` : ''}};
`,
  );
  return { count: pngs.length, total };
}
