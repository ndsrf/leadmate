// Builds the single-file simulation bundle and embeds it as a string the native shell can load
// without any network (works with Expo tunnels). Output: src/shell/simHtml.generated.ts
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

execSync('npx vite build --config bundle/vite.config.mts', { stdio: 'inherit', env: { ...process.env, VITE_CONFIG_NATIVE_IGNORE_WARNING: 'true' } });
const html = readFileSync('bundle/dist/index.html', 'utf8');
writeFileSync('src/shell/simHtml.generated.ts', `// generated by scripts/embed-sim.mjs — do not edit\nexport const SIM_HTML: string | null = ${JSON.stringify(html)};\n`);
console.log(`embedded ${(html.length / 1024).toFixed(0)} kB`);
